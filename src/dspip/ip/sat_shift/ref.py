"""Reference and vector generator of ``sat_shift``.

``y = sat(W_OUT, rshift_round(x, SHIFT))`` — signed (``SIGNED=1``) or unsigned saturation.
Each vector set is a directory with ``x.txt``, ``y.txt`` and ``dims.svh``; the set names
encode the parameters so the same generator serves several configurations.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from dspip.fixed import rshift_round_py, saturate_py, saturate_u_py
from dspip.vectors import read_ints, write_ints

SETS = {
    #  name:        (w_in, shift, w_out, signed, n, seed)
    "signed_w40_s12_o16": (40, 12, 16, 1, 3000, 1),
    "signed_w16_s0_o12": (16, 0, 12, 1, 2000, 2),
    "unsigned_w32_s16_o16": (32, 16, 16, 0, 2000, 3),
}


def model(x: int, shift: int, w_out: int, signed: int) -> int:
    v = rshift_round_py(x, shift)
    return saturate_py(v, w_out) if signed else saturate_u_py(v, w_out)


def stimulus(w_in: int, signed: int, n: int, seed: int) -> list[int]:
    """Random words plus the corners the semantics live on: both ends of the range, exact
    half-LSB ties on negative and positive values, zero."""
    rng = np.random.default_rng(seed)
    lo, hi = (-(1 << (w_in - 1)), (1 << (w_in - 1)) - 1) if signed else (0, (1 << w_in) - 1)
    vals = [int(v) for v in rng.integers(lo, hi + 1, size=n - 16, dtype=np.int64)]
    corners = [lo, hi, 0, 1, -1 if signed else 2, lo + 1, hi - 1]
    for s in (1, 2, 5, 12, 16):
        half = 1 << (s - 1)
        corners += [half, 3 * half, (-half) if signed else half + 1, (-3 * half) if signed else 0]
    corners = [min(max(c, lo), hi) for c in corners][:16]
    return vals + corners


def vectors() -> dict[str, tuple[list[int], int, int, list[int]]]:
    out = {}
    for name, (w_in, shift, w_out, signed, n, seed) in SETS.items():
        x = stimulus(w_in, signed, n, seed)
        y = [model(v, shift, w_out, signed) for v in x]
        out[name] = (x, shift, w_out, y)
    return out


def dims_svh(w_in: int, shift: int, w_out: int, signed: int, n: int) -> str:
    return "\n".join([
        "// Generated by dspip.ip.sat_shift.ref — do not edit.",
        f"localparam int W_IN      = {w_in};",
        f"localparam int SHIFT     = {shift};",
        f"localparam int W_OUT     = {w_out};",
        f"localparam int SIGNED    = {signed};",
        f"localparam int N_SAMPLES = {n};",
    ]) + "\n"


def generate(set_name: str, out_dir: Path) -> None:
    w_in, shift, w_out, signed, n, seed = SETS[set_name]
    x = stimulus(w_in, signed, n, seed)
    y = [model(v, shift, w_out, signed) for v in x]
    assert any(abs(v) == (1 << (w_out - 1)) - 1 or v == -(1 << (w_out - 1)) for v in y) or not signed
    out_dir.mkdir(parents=True, exist_ok=True)
    write_ints(out_dir / "x.txt", x)
    write_ints(out_dir / "y.txt", y)
    (out_dir / "dims.svh").write_text(dims_svh(w_in, shift, w_out, signed, len(x)))


def probe(set_dir: Path, sample: int) -> str:
    w_in, shift, w_out, signed, _n, _seed = SETS[set_dir.name]
    x = read_ints(set_dir / "x.txt")[sample]
    v = rshift_round_py(x, shift)
    return (f"x={x} rshift_round(x,{shift})={v} sat({'s' if signed else 'u'}{w_out})="
            f"{model(x, shift, w_out, signed)}")
